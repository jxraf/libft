#include "libft.h"

int	ft_strncmp(const char *s1, const char *s2, size_t n)
{
	unsigned int	x;

	x = 0;
	while ((s1[x] || s2[x]) && n > 0)
	{
		if (s1[x] != s2[x])
			return (s1[x] - s2[x]);
		x++;
		n--;
	}
	return (0);
}
